import os
import pandas as pd
from data.validation import validate_ohlcv, DataValidationError


def load_historical_data(ticker: str, interval: str, start: str | None = None, end: str | None = None) -> pd.DataFrame:
    """
    Loads historical data from local CSV files generated by download_polygon_data.py
    and validates canonical OHLCV invariants.
    """
    current_dir = os.path.dirname(os.path.abspath(__file__))
    csv_dir = os.path.join(current_dir, "historical_csvs")
    filename = f"{ticker}_{interval}_{start}_to_{end}.csv"
    filepath = os.path.join(csv_dir, filename)

    if not os.path.exists(filepath):
        # Fallback: check if any matching historical file for this ticker and interval exists
        matching = []
        if os.path.isdir(csv_dir):
            prefix = f"{ticker}_{interval}_"
            matching = [f for f in os.listdir(csv_dir) if f.startswith(prefix) and f.endswith(".csv")]
            if not matching:
                # also check ticker prefix
                matching = [f for f in os.listdir(csv_dir) if f.startswith(f"{ticker}_") and f.endswith(".csv")]

        if matching:
            filename = sorted(matching)[-1]
            filepath = os.path.join(csv_dir, filename)
            print(f"Loading local data from fallback file: {filename}...")
        else:
            print(f"❌ Error: Could not find historical data file for {ticker}.")
            print(f"Please run 'python data/download_polygon_data.py' first to generate: {filepath}")
            return pd.DataFrame()
    else:
        print(f"Loading local data from {filename}...")

    df = pd.read_csv(filepath)

    try:
        norm_df, _ = validate_ohlcv(df, raise_on_error=True, timeframe=interval)
    except DataValidationError as e:
        print(f"❌ Error validating historical data for {ticker}: {e}")
        return pd.DataFrame()

    # Optional date slicing
    if start or end:
        try:
            if start and end:
                norm_df = norm_df.loc[start:end]
            elif start:
                norm_df = norm_df.loc[start:]
            elif end:
                norm_df = norm_df.loc[:end]
        except Exception:
            pass

    return norm_df
